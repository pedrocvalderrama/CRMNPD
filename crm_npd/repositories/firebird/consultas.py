def anexar_and(sql: str, clausula: str) -> str:
    """Acrescenta um AND/WHERE a um SELECT canonico, sem alterar as regras."""
    texto = (sql or "").strip().rstrip(";")
    clausula = (clausula or "").strip()
    if not texto or not clausula:
        return texto
    if re.search(r"\bWHERE\b", texto, flags=re.IGNORECASE):
        return f"{texto}\n  AND {clausula}"
    return f"{texto}\nWHERE {clausula}"


def in_trim(coluna: str, quantidade: int) -> str:
    """Clausula IN parametrizada, com TRIM para VARCHAR do Sisplan."""
    n = max(0, int(quantidade or 0))
    marcas = ",".join("?" for _ in range(n))
    return f"TRIM(COALESCE({coluna}, '')) IN ({marcas})"


def sql_cdc_max_log_alteracao() -> str:
    return "SELECT MAX(ID) FROM LOG_ALTERACAO"


def sql_cdc_max_log() -> str:
    return "SELECT MAX(ID) FROM LOG"


def sql_cdc_log_alteracao(lote: int = 2000) -> str:
    n = max(1, min(int(lote or 2000), 5000))
    return f"""
SELECT FIRST {n} ID, TABELA, TELA, CAMPO_CHAVE
FROM LOG_ALTERACAO
WHERE ID > ?
ORDER BY ID ASC
"""


def sql_cdc_log(lote: int = 2000) -> str:
    n = max(1, min(int(lote or 2000), 5000))
    return f"""
SELECT FIRST {n} ID, TELA, OPERACAO, CHAVE, TABELA, DESCRICAO
FROM LOG
WHERE ID > ?
ORDER BY ID ASC
"""
