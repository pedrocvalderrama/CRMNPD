"""SELECTs canonicos do Sisplan, copiados do manual de acesso.

Nenhuma destas consultas escreve. Parametros de data entram como ``?``.
"""

from __future__ import annotations

FATURAMENTO_LIQUIDO = """
SELECT
    N.DT_EMISSAO AS DT_EMISSAO,
    N.FATURA AS FATURA,
    N.CODREP AS CODREP,
    COALESCE(REP.NOME, '') AS REP_NOME,
    N.CODCLI AS CODCLI,
    COALESCE(E.NOME, '') AS CLI_NOME,
    COALESCE(E.FANTASIA, E.NOME) AS FANTASIA,
    PROD.CODIGO AS CODIGO,
    PROD.DESCRICAO AS DESCRICAO,
    CAST(NI.QTDE AS DOUBLE PRECISION) AS QTDE,
    CAST(NI.VALOR_LIQ AS DOUBLE PRECISION) AS VALOR_LIQ,
    NAT.TIPO AS NAT_TIPO,
    CAST(COALESCE(NI.VALOR_FRETE, 0) AS DOUBLE PRECISION) AS VALOR_FRETE
FROM NOTAITEN_001 NI
INNER JOIN NOTA_001 N ON (N.FATURA = NI.FATURA)
INNER JOIN PRODUTO_001 PROD ON (PROD.CODIGO = NI.CODIGO)
INNER JOIN NATUREZA_001 NAT ON (NAT.NATUREZA = NI.NATUREZA)
LEFT JOIN ENTIDADE_001 E ON (E.CODCLI = N.CODCLI)
LEFT JOIN REPRESEN_001 REP ON (REP.CODREP = N.CODREP)
WHERE N.DT_EMISSAO BETWEEN ? AND ?
  AND NAT.TIPO IN ('V', 'D')
  AND (N.MOTIVO_CANCEL IS NULL OR TRIM(N.MOTIVO_CANCEL) = '')
ORDER BY N.FATURA
"""

PEDIDOS = """
SELECT
    P.NUMERO AS PEDIDO,
    P.DT_EMISSAO AS DT_EMISSAO,
    P.CODCLI AS CODCLI,
    P.CODREP AS CODREP,
    COALESCE(E.NOME, '') AS CLI_NOME,
    COALESCE(E.FANTASIA, E.NOME) AS FANTASIA,
    COALESCE(REP.NOME, '') AS REP_NOME,
    CAST(PI.QTDE AS DOUBLE PRECISION) AS QTDE,
    CAST(PI.QTDE_F AS DOUBLE PRECISION) AS QTDE_F,
    CAST(PI.QTDE_CANC AS DOUBLE PRECISION) AS QTDE_CANC,
    CAST(COALESCE(PI.PRECO, 0) AS DOUBLE PRECISION) AS PRECO,
    PROD.CODIGO AS CODIGO,
    PROD.DESCRICAO AS DESCRICAO
FROM PED_ITEN_001 PI
INNER JOIN PEDIDO_001 P ON (P.NUMERO = PI.NUMERO)
INNER JOIN PRODUTO_001 PROD ON (PROD.CODIGO = PI.CODIGO)
LEFT JOIN ENTIDADE_001 E ON (E.CODCLI = P.CODCLI)
LEFT JOIN REPRESEN_001 REP ON (REP.CODREP = P.CODREP)
WHERE P.DT_EMISSAO BETWEEN ? AND ?
ORDER BY P.NUMERO
"""

LIQUIDEZ = """
SELECT
    R.NUMERO AS TITULO,
    R.PARCELA AS PARCELA,
    R.CODCLI AS CODCLI,
    R.DT_EMISSAO AS DT_EMISSAO,
    R.DT_VENCTO AS DT_VENCTO,
    CAST(R.VALOR2 AS DOUBLE PRECISION) AS VALOR,
    CAST(COALESCE(R.VALOR_PAGO, 0) AS DOUBLE PRECISION) AS VALOR_PAGO,
    R.STATUS AS STATUS
FROM RECEBER_001 R
WHERE R.STATUS = 'DUPL'
  AND COALESCE(R.VAL_DEV, 0) BETWEEN 0.00 AND 0.10
  AND R.DT_EMISSAO BETWEEN ? AND ?
ORDER BY R.DT_EMISSAO, R.NUMERO, R.PARCELA
"""
